def test_synchronous_accounting_even_when_operation_fails():
    trace = []
    wall, cpu = iter([10.0, 13.0]), iter([2.0, 3.5])
    def operation():
        trace.append("fit")
        raise RuntimeError("software failure")
    value, timing, error = engines.measure(operation, synchronize=lambda: trace.append("sync"),
                                           resources=Resources(), wall_clock=lambda: next(wall), cpu_clock=lambda: next(cpu))
    assert trace == ["sync", "fit", "sync"]
    assert value is None and isinstance(error, RuntimeError)
    assert timing["wall_seconds"] == 3.0 and timing["cpu_process_seconds"] == 1.5
    assert timing["peak_rss_bytes"] == 123


