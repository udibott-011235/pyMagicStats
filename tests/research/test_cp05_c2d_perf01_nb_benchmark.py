def test_workload_loader_delegates_accepted_provenance_and_stored_bytes(tmp_path, records):
    files = [tmp_path / name for name in ("workload", "archive", "crossings")]
    for file in files:
        file.write_bytes(file.name.encode())
    manifest = ROOT / bm.SOURCE_PATH
