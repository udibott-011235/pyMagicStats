def test_cuda_stage_events_explicitly_synchronized():
    trace = []
    class Event:
        def __init__(self):
            self.index = len([item for item in trace if item == "event"])
            trace.append("event")
        def record(self):
            trace.append("record" + str(self.index))
    cuda = engines.CudaEngine.__new__(engines.CudaEngine)
    cuda.cp = SimpleNamespace(cuda=SimpleNamespace(Event=Event, get_elapsed_time=lambda a, b: 1500.0),
                              get_default_memory_pool=lambda: SimpleNamespace(total_bytes=lambda: 512))
    cuda.synchronize = lambda: trace.append("sync")
    cuda.memory_peak = 0
    value, wall, device = cuda._stage(lambda: trace.append("fit") or 42)
    assert trace == ["sync", "event", "event", "record0", "fit", "record1", "sync"]
    assert value == 42 and wall >= 0 and device == 1.5 and cuda.memory_peak == 512


