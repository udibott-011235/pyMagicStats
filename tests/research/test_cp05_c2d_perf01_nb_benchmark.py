def good():
    return {"classification": "ELIGIBLE", "converged": True, "parameters": {"r": 1.0, "p": 0.5},
            "log_likelihood": -10.0, "failure_reason": None}


def rows(records):
    return [bm.evidence(record, good()) for record in records]


class Resources:
    peak = 123
    def __enter__(self):
        return self
    def __exit__(self, *args):
        pass


def software_measure(operation, **kwargs):
    try:
        operation()
        error = None
    except Exception as exc:
        error = exc
    return None, {"wall_seconds": 2.0, "cpu_process_seconds": 1.0, "peak_rss_bytes": 123}, error


