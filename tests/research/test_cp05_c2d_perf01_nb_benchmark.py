def toy_workload():
    """2400 distinct identities with repeated literal transport-test bytes."""
    payload = SamplePayload.from_sample(np.array([0, 0, 0, 1, 8], dtype="<i8")).serialize()
    outers = []
    for outer_index in range(12):
        cell = f"negative_binomial|SOFTWARE_TEST={outer_index}|n=5|CVM|composite"
        identity = f"{cell}|raw_outer={outer_index}"
        accepted = [{"identity": f"{identity}|raw_inner={3 * ordinal + 2}",
                     "raw_inner_index": 3 * ordinal + 2, "seed_identity": 100 + ordinal,
                     "payload": copy.deepcopy(payload)} for ordinal in range(199)]
        outers.append({"cell_id": cell, "raw_outer_index": outer_index,
                       "observed": {"identity": identity, "seed_identity": 7, "payload": copy.deepcopy(payload)},
                       "accepted": accepted})
    return {"B_R11": 199, "outers": outers}


